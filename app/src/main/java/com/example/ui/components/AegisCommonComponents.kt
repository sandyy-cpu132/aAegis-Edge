/**
 * Enforces Android 14+ (API 34+) `accessibilityDataSensitive = ACCESSIBILITY_DATA_SENSITIVE_YES`
 * on the hosting Root View while a sensitive screen (Autofill Vault, Security Settings,
 * Encryption Status) is displayed (Part 3.4).
 */
@Composable
fun SensitiveScreenProtectionEffect() {
    val hostView = LocalView.current
    DisposableEffect(hostView) {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.UPSIDE_DOWN_CAKE) {
            hostView.setAccessibilityDataSensitive(View.ACCESSIBILITY_DATA_SENSITIVE_YES)
        }
        onDispose {
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.UPSIDE_DOWN_CAKE) {
                hostView.setAccessibilityDataSensitive(View.ACCESSIBILITY_DATA_SENSITIVE_AUTO)
            }
        }
    }
}

