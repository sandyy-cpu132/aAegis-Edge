@Composable
fun StatusPill(
    label: String,
    isPositive: Boolean
) {
    val bgColor = if (isPositive) {
        Color(0xFF10B981).copy(alpha = 0.16f)
    } else {
        Color(0xFFF59E0B).copy(alpha = 0.16f)
    }
    val fgColor = if (isPositive) {
        Color(0xFF10B981)
    } else {
        Color(0xFFF59E0B)
    }
    Surface(
        shape = RoundedCornerShape(50),
        color = bgColor,
        border = BorderStroke(1.dp, fgColor.copy(alpha = 0.4f))
    ) {
        Text(
            text = label,
            style = MaterialTheme.typography.labelMedium,
            color = fgColor,
            modifier = Modifier.padding(horizontal = 10.dp, vertical = 4.dp)
        )
    }
}

